test('meaningful additions ignore blanks, braces, comments and generated files', () => {
  const patch = ['@@ -1,2 +1,8 @@', '+const a = 1;', '+', '+   ', '+}', '+// comment', '+export function f() {', '+  return a + 1;', ' context', '-removed'].join('\n');
  assert.deepEqual(countMeaningfulAdditions(patch), { meaningful: 3, added: 7, generated: false, patchMissing: false });
  const gen = ['+// @generated by protoc', '+const x = 1;'].join('\n');
  assert.equal(countMeaningfulAdditions(gen).meaningful, 0);
  assert.equal(countMeaningfulAdditions(undefined).patchMissing, true);
});

// ------------------------------------------------------------ Wallet auth
const B58 = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';
function base58Encode(bytes) {
  let n = BigInt('0x' + (Buffer.from(bytes).toString('hex') || '0'));
  let out = '';
  while (n > 0n) {
    out = B58[Number(n % 58n)] + out;
    n /= 58n;
  }
  for (const b of bytes) {
    if (b === 0) out = '1' + out;
    else break;
  }
  return out;
}

test('verifies a real ed25519 signature from a Solana-style address', () => {
  const { publicKey, privateKey } = generateKeyPairSync('ed25519');
  const raw = Buffer.from(publicKey.export({ format: 'jwk' }).x, 'base64url');
  const address = base58Encode(raw);
  const message = Buffer.from(buildSignInMessage({ domain: 'localhost:4010', address, nonce: newNonce(), issuedAt: new Date().toISOString() }));
  const signature = sign(null, message, privateKey);

  assert.equal(verifySolanaSignature(address, message, signature), true);
  const tampered = Buffer.from(message);
  tampered[0] ^= 1;
  assert.equal(verifySolanaSignature(address, tampered, signature), false);
  assert.equal(verifySolanaSignature('0x52908400098527886E0F7030069857D2E4169EE7', message, signature), false);
});
