// ------------------------------------------------------------ LeetCode
// Synthetic page that mirrors the structure Firecrawl returned for a real profile.
const profile = (solved, entries, summary = 'Coding every day') => `
![Avatar](https://assets.leetcode.com/users/demo/avatar.png)

demo_user

Rank12,345

${summary}

Community Stats

${solved}/4115

Solved

Easy

10/976

Recent AC

List

${entries.map(([t, ago, id]) => `[${t}${ago}](https://leetcode.com/submissions/detail/${id}/)`).join(' ')}
`;

test('agoToSeconds', () => {
  assert.equal(agoToSeconds('3 days ago'), 3 * 86400);
  assert.equal(agoToSeconds('an hour ago'), 3600);
  assert.equal(agoToSeconds('a month ago'), 30 * 86400);
  assert.equal(agoToSeconds('just now'), null);
});

test('parses solved count and recent accepted submissions', () => {
  const md = profile(42, [
    ['Two Sum', '5 minutes ago', '2200000002'],
    ['Count Valid Substrings II', '13 days ago', '2191420316'],
  ]);
  const p = parseLeetCodeProfile(md);
  assert.equal(p.solved, 42);
  assert.equal(p.totalProblems, 4115);
  assert.equal(p.hasRecentAcSection, true);
  assert.deepEqual(
    p.recentAccepted.map((r) => [r.title, r.ago, r.submissionId]),
    [
      ['Two Sum', '5 minutes ago', '2200000002'],
      ['Count Valid Substrings II', '13 days ago', '2191420316'],
    ],
  );
});

test('missing data gives nulls, not crashes', () => {
  const p = parseLeetCodeProfile('This profile is private');
  assert.equal(p.solved, null);
  assert.deepEqual(p.recentAccepted, []);
  assert.equal(p.hasRecentAcSection, false);
});

test('verification code must match as a whole token', () => {
  const md = profile(1, [], 'Hi! CS-VERIFY-7F3KQ2 is my code');
  assert.equal(containsVerificationCode(md, 'CS-VERIFY-7F3KQ2'), true);
  assert.equal(containsVerificationCode(md, 'CS-VERIFY-7F3K'), false);
  assert.equal(containsVerificationCode(profile(1, [], 'XCS-VERIFY-7F3KQ2'), 'CS-VERIFY-7F3KQ2'), false);
});

test('snapshot diff finds only newer submissions and the solved delta', () => {
  const before = parseLeetCodeProfile(profile(41, [['Old', '2 days ago', '2190000000']]));
  const after = parseLeetCodeProfile(
    profile(42, [
      ['New', '3 minutes ago', '2200000005'],
      ['Old', '2 days ago', '2190000000'],
    ]),
  );
  const d = diffSnapshots(before, after);
  assert.equal(d.solvedDelta, 1);
  assert.deepEqual(d.newAccepted.map((r) => r.submissionId), ['2200000005']);
});

test('re-solving an old problem: new submission but no solved-count increase', () => {
  const before = parseLeetCodeProfile(profile(42, [['Two Sum', '2 days ago', '2190000000']]));
  const after = parseLeetCodeProfile(profile(42, [['Two Sum', '1 minute ago', '2200000009']]));
  const d = diffSnapshots(before, after);
  assert.equal(d.newAccepted.length, 1);
  assert.equal(d.solvedDelta, 0);
});

