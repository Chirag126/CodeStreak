// Early version of the GitHub "meaningful lines" rule (Phase 24 refines it).
// Counts added lines in a unified-diff patch that look like real code.

export const ELIGIBLE_EXTENSIONS = ['.ts', '.tsx', '.js', '.jsx', '.rs', '.py', '.cpp', '.go'];

const EXCLUDED_PATH = [
  /(^|\/)node_modules\//,
  /(^|\/)(dist|build|out|\.next|target|vendor|coverage)\//,
  /\.min\.(js|css)$/,
  /(^|\/)(package-lock\.json|pnpm-lock\.yaml|yarn\.lock|Cargo\.lock|go\.sum)$/,
];

const GENERATED_MARKERS = /@generated|DO NOT EDIT|auto-generated|autogenerated/i;

export function isEligibleFile(filename) {
  const f = String(filename).toLowerCase();
  if (EXCLUDED_PATH.some((re) => re.test(f))) return false;
  return ELIGIBLE_EXTENSIONS.some((ext) => f.endsWith(ext));
}

function isCommentOnly(line) {
  return /^(\/\/|#|\/\*|\*\/|\*|--)/.test(line);
}

function isPunctuationOnly(line) {
  return /^[\s{}()[\];,.:]*$/.test(line);
}

/**
 * @param {string|undefined} patch  GitHub `files[].patch` (absent for large or binary diffs)
 * @returns {{ meaningful: number, added: number, generated: boolean, patchMissing: boolean }}
 */
export function countMeaningfulAdditions(patch) {
  if (typeof patch !== 'string') return { meaningful: 0, added: 0, generated: false, patchMissing: true };
  let added = 0;
  let meaningful = 0;
  let generated = false;
  for (const raw of patch.split('\n')) {
    if (!raw.startsWith('+') || raw.startsWith('+++')) continue;
    added++;
    const line = raw.slice(1).trim();
    if (GENERATED_MARKERS.test(line)) generated = true;
    if (!line || isCommentOnly(line) || isPunctuationOnly(line)) continue;
    meaningful++;
  }
  return { meaningful: generated ? 0 : meaningful, added, generated, patchMissing: false };
}
