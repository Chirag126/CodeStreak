#!/usr/bin/env node
// Copies the program's IDL from `anchor build` output into packages/shared (zero dependencies).
//
// Usage:
//   node scripts/sync-idl.mjs           # write packages/shared/src/program/idl/*
//   node scripts/sync-idl.mjs --check   # CI: fail if the committed IDL differs from the build
//   node scripts/sync-idl.mjs --from <dir with codestreak.json and codestreak.ts>
//
// Run it after any change to the program's instructions, accounts, events or errors.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'packages/shared/src/program/idl');
const HEADER = '// GENERATED by scripts/sync-idl.mjs from `anchor build` output. Do not edit by hand.\n';

const args = process.argv.slice(2);
const check = args.includes('--check');
const fromIdx = args.indexOf('--from');
const jsonPath = fromIdx >= 0 ? path.join(args[fromIdx + 1], 'codestreak.json') : path.join(ROOT, 'target/idl/codestreak.json');
const typesPath = fromIdx >= 0 ? path.join(args[fromIdx + 1], 'codestreak.ts') : path.join(ROOT, 'target/types/codestreak.ts');

for (const p of [jsonPath, typesPath]) {
  if (!existsSync(p)) {
    console.error(`missing ${p}: run \`anchor build\` first`);
    process.exit(1);
  }
}

const normalize = (s) => s.replace(/\r\n/g, '\n');
const idl = JSON.parse(readFileSync(jsonPath, 'utf8'));
const types = normalize(readFileSync(typesPath, 'utf8')).trimEnd() + '\n';

const outputs = {
  'codestreak.types.ts': HEADER + types,
  'codestreak.idl.ts':
    HEADER +
    "import type { Codestreak } from './codestreak.types.js';\n\n" +
    '/** The program IDL exactly as `anchor build` emits it (snake_case JSON). */\n' +
    `export const CODESTREAK_IDL_JSON = ${JSON.stringify(idl, null, 2)} as const;\n\n` +
    "/** The same IDL, typed for @anchor-lang/core's `Program` (its TypeScript type is the camelCase view). */\n" +
    'export const CODESTREAK_IDL = CODESTREAK_IDL_JSON as unknown as Codestreak;\n',
};

let stale = 0;
for (const [name, content] of Object.entries(outputs)) {
  const file = path.join(OUT_DIR, name);
  const current = existsSync(file) ? normalize(readFileSync(file, 'utf8')) : null;
  if (current === content) {
    console.log(`up to date  ${path.relative(ROOT, file)}`);
    continue;
  }
  if (check) {
    console.error(`STALE       ${path.relative(ROOT, file)}`);
    stale++;
  } else {
    mkdirSync(OUT_DIR, { recursive: true });
    writeFileSync(file, content);
    console.log(`written     ${path.relative(ROOT, file)}`);
  }
}
if (stale > 0) {
  console.error('\nThe committed IDL does not match the program. Run `anchor build` and `node scripts/sync-idl.mjs`, then commit.');
  process.exit(1);
}
